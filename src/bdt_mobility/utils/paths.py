class PathTemplate(PurePosixPath):
    """A PurePosixPath with unresolved ``{variable}`` placeholders.

    Build with the usual ``/`` operator, then call ``.substitute(**kwargs)``
    to get a concrete ``Path``.  The placeholder syntax is identical to
    ``str.format_map``, which makes future migration to Python 3.14
    t-strings a one-character change per constant.

    Example::

        PLATOONS_SEED = PathTemplate(TRAFFIC_SIMULATOR, "platoons_seed_{seed}.parquet")
        path = PathRegistry.PLATOONS_SEED.substitute(seed=3)
    """

    def substitute(self, **kwargs: Any) -> Path:
        return Path(str(self).format_map(kwargs))


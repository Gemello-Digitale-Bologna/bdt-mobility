#!/usr/bin/env python3
"""Generate the three DigitalHub platform files from the single source of truth.

Reads PIPELINE (order) and each step's MAIN_OUTPUTS (what to log) and
produces three files under src/bdt_mobility/extraction/platform/:

  workflow_handlers.py  — Nuclio serverless handlers decorated with @handler
  workflow.py           — Hera sequential DAG
  ingest_data.py        — DigitalHub function-registration script

Re-run whenever PIPELINE order changes or any step's MAIN_OUTPUTS changes:

    uv run python scripts/generate_platform.py

A fingerprint of (module_name, outputs) is embedded in each generated file.
Call workflow_handlers._verify() to detect staleness at runtime.
"""

from __future__ import annotations

import hashlib
import importlib
import json
import sys
from pathlib import Path, PurePosixPath

# Make src/ importable when running from the project root.
sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from bdt_mobility.extraction.pipeline import PIPELINE
from bdt_mobility.extraction.platform.outputs import DynamicPlatformOutputs, PlatformOutput
from bdt_mobility.utils.paths import PathRegistry

PLATFORM_DIR = Path("src/bdt_mobility/extraction/platform")
DH_STEP_PREFIX = "data-ingestion-step"
REPO_URL = "https://github.com/Gemello-Digitale-Bologna/bdt-mobility"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _get_outputs(step):
    m = importlib.import_module(step.__name__)
    return getattr(m, "MAIN_OUTPUTS", [])


def _compute_fingerprint(pipeline) -> str:
    items = []
    for step in pipeline:
        outputs = _get_outputs(step)
        if isinstance(outputs, list):
            sig = [("static", o.name, o.kind) for o in outputs]
        elif isinstance(outputs, DynamicPlatformOutputs):
            sig = [("dynamic", str(outputs.directory.relative_to(PathRegistry.DATA)), outputs.kind)]
        else:
            sig = [("unknown",)]
        items.append((step.__name__, sig))
    return hashlib.sha256(json.dumps(items, sort_keys=True).encode()).hexdigest()[:16]


def _fn_name(i: int) -> str:
    return f"step_{i}"


def _dh_name(i: int) -> str:
    return f"{DH_STEP_PREFIX}-{i}"


def _registry_attr(path: Path) -> str:
    """Return 'PathRegistry.ATTR' for the PathRegistry attribute equal to path."""
    for attr, val in PathRegistry.__dict__.items():
        if attr.startswith("_"):
            continue
        if isinstance(val, PurePosixPath) and val == path:
            return f"PathRegistry.{attr}"
    return repr(str(path))


def _log_call(project_var: str, out: PlatformOutput) -> str:
    method = "log_artifact" if out.kind == "artifact" else "log_dataitem"
    path_expr = _registry_attr(out.path)
    return f"{project_var}.{method}({out.name!r}, kind={out.kind!r}, source=str({path_expr}))"


# ---------------------------------------------------------------------------
# workflow_handlers.py
# ---------------------------------------------------------------------------


def _gen_handlers(pipeline, fp: str) -> str:
    lines: list[str] = []

    lines += [
        '"""Auto-generated by scripts/generate_platform.py — DO NOT EDIT.',
        "",
        "Re-run after changing PIPELINE or any step's MAIN_OUTPUTS.",
        f"Fingerprint: {fp}",
        '"""',
        "from __future__ import annotations",
        "",
        "import importlib",
        "import typing",
        "",
        "from digitalhub_runtime_python import handler",
        "",
        "from bdt_mobility.utils.paths import PathRegistry",
        "",
        "if typing.TYPE_CHECKING:",
        "    from digitalhub.entities.artifact._base.entity import Artifact",
        "    from digitalhub.entities.dataitem.table.entity import DataitemTable",
        "    from digitalhub.entities.project._base.entity import Project",
        "    from nuclio_sdk import Context",
        "",
        f'_FINGERPRINT = "{fp}"',
        "",
        "",
        "def _verify() -> None:",
        '    """Raise RuntimeError if MAIN_OUTPUTS have changed since generation."""',
        "    import hashlib",
        "    import json",
        "    from bdt_mobility.extraction.pipeline import PIPELINE",
        "    from bdt_mobility.extraction.platform.outputs import DynamicPlatformOutputs",
        "    items = []",
        "    for step in PIPELINE:",
        "        m = importlib.import_module(step.__name__)",
        '        outputs = getattr(m, "MAIN_OUTPUTS", [])',
        "        if isinstance(outputs, list):",
        '            sig = [("static", o.name, o.kind) for o in outputs]',
        "        elif isinstance(outputs, DynamicPlatformOutputs):",
        '            sig = [("dynamic", str(outputs.directory.relative_to(PathRegistry.DATA)), outputs.kind)]',
        "        else:",
        '            sig = [("unknown",)]',
        "        items.append((step.__name__, sig))",
        "    fp = hashlib.sha256(json.dumps(items, sort_keys=True).encode()).hexdigest()[:16]",
        "    if fp != _FINGERPRINT:",
        "        raise RuntimeError(",
        '            f"workflow_handlers.py is stale (computed {fp!r}, embedded {_FINGERPRINT!r}). "',
        '            "Run: uv run python scripts/generate_platform.py"',
        "        )",
        "",
        "",
        "def _tag_list(",
        "    entities: list[DataitemTable | Artifact],",
        "    labels: list[str] | str | None,",
        ") -> None:",
        "    if labels is not None:",
        "        if isinstance(labels, str):",
        "            labels = [labels]",
        "        for e in entities:",
        "            e.metadata.labels = labels",
        "            e.save(update=True)",
        "",
        "",
        "def _exec_main(module_name: str):",
        '    """Import module_name and call its main(); return whatever main() returns."""',
        "    m = importlib.import_module(module_name)",
        '    return getattr(m, "main")()',
        "",
        "",
        "_verify()  # abort import if handlers are stale",
        "",
    ]

    for i, step in enumerate(pipeline):
        outputs = _get_outputs(step)
        fn = _fn_name(i)
        module = step.__name__
        lines.append("")

        if isinstance(outputs, list) and len(outputs) == 0:
            lines += [
                f"# Step {i}: {module}",
                f'def {fn}(context: "Context", labels: list[str] | str | None = None) -> None:',
                f'    context.logger.info("Executing: {module}")',
                f'    _exec_main("{module}")',
            ]

        elif isinstance(outputs, list):
            output_names = [o.name for o in outputs]
            lines += [
                f"# Step {i}: {module}",
                f"@handler(outputs={output_names!r})",
                f"def {fn}(",
                '    project: "Project",',
                '    context: "Context",',
                "    labels: list[str] | str | None = None,",
                ") -> None:",
                f'    context.logger.info("Executing: {module}")',
                f'    _exec_main("{module}")',
            ]
            var_names = []
            for j, out in enumerate(outputs):
                var = f"d{j + 1}"
                var_names.append(var)
                lines.append(f"    {var} = {_log_call('project', out)}")
            lines.append(f"    _tag_list([{', '.join(var_names)}], labels)")

        elif isinstance(outputs, DynamicPlatformOutputs):
            log_fn = "log_artifact" if outputs.kind == "artifact" else "log_dataitem"
            lines += [
                f"# Step {i}: {module}",
                "@handler()",
                f"def {fn}(",
                '    project: "Project",',
                '    context: "Context",',
                "    labels: list[str] | str | None = None,",
                ") -> None:",
                f'    context.logger.info("Executing: {module}")',
                f'    names = _exec_main("{module}")',
                "    dataitems = []",
                "    for name, path in names:",
                f'        d = project.{log_fn}(name, kind={outputs.kind!r}, source=str(path))',
                "        dataitems.append(d)",
                "    _tag_list(dataitems, labels)",
            ]

    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# workflow.py
# ---------------------------------------------------------------------------


def _gen_workflow(pipeline, fp: str) -> str:
    n = len(pipeline)
    s_vars = [f"S_{i}" for i in range(n)]

    lines: list[str] = [
        '"""Auto-generated by scripts/generate_platform.py — DO NOT EDIT.',
        "",
        "Re-run after changing PIPELINE.",
        f"Fingerprint: {fp}",
        '"""',
        "from __future__ import annotations",
        "",
        "from digitalhub_runtime_hera.dsl import step",
        "from hera.workflows import DAG, Parameter, Workflow",
        "",
        f'_FINGERPRINT = "{fp}"',
        "",
        "common_template = dict(",
        '    action="job",',
        '    secrets=["GIT_TOKEN"],',
        "    envs=[",
        '        {"name": "PYTHONPATH", "value": "$PYTHONPATH:."},',
        '        {"name": "BDT_DATA_ROOT", "value": "/mnt/data"},',
        "    ],",
        '    resources={"mem": "16Gi", "cpu": "3", "disk": "10Gi"},',
        "    parameters={",
        '        "labels": "{{workflow.parameters.labels}}",',
        "    },",
        ")",
        "",
        "",
        "def pipeline():",
        '    with Workflow(entrypoint="dag", arguments=Parameter(name="labels")) as w:',
        '        with DAG(name="dag"):',
    ]

    for i in range(n):
        lines.append(
            f'            {s_vars[i]} = step(function="{_dh_name(i)}", template=common_template)'
        )

    lines.append("            (")
    lines.append(f"                {s_vars[0]}")
    for var in s_vars[1:]:
        lines.append(f"                >> {var}")
    lines.append("            )")
    lines.append("    return w")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# ingest_data.py
# ---------------------------------------------------------------------------


def _gen_ingest(pipeline, fp: str) -> str:
    base_path = "src.bdt_mobility.extraction.platform.workflow_handlers"

    lines: list[str] = [
        '"""Auto-generated by scripts/generate_platform.py — DO NOT EDIT.',
        "",
        "Registers per-step DigitalHub functions and runs the data-ingestion Hera workflow.",
        "Run from the platform/ directory (reads local req.txt).",
        "",
        f"Fingerprint: {fp}",
        '"""',
        "from pathlib import Path",
        "import digitalhub as dh",
        "from bdt_mobility.extraction.config import PROJECT_NAME, TAG_GITHUB",
        "",
        "project = dh.get_project(PROJECT_NAME)",
        "",
        "path = Path(__file__).parent / 'req.txt'",
        "with open(path) as f:",
        "    requirements = f.read().splitlines()",
        "",
        "function_build = project.new_function(",
        '    name="data-ingestion-build",',
        '    kind="python",',
        '    python_version="PYTHON3_12",',
        f'    code_src=f"git+{REPO_URL}#{{TAG_GITHUB}}",',
        '    handler="placeholder",',
        "    requirements=requirements,",
        '    base_image="ghcr.io/scc-digitalhub/digitalhub-serverless/python-runtime:3.12-0.14.4",',
        ")",
        'function_build.run("build", secrets=["GIT_TOKEN"], wait=True)',
        "function_build.refresh()",
        "",
        "shared_kwargs = dict(",
        '    kind="python",',
        '    python_version="PYTHON3_12",',
        f'    code_src=f"git+{REPO_URL}#{{TAG_GITHUB}}",',
        "    image=function_build.spec.image,",
        ")",
        "",
        f'base_path = "{base_path}"',
        "tuple_step_handler = (",
    ]

    for i in range(len(pipeline)):
        lines.append(f'    ("{_dh_name(i)}", f"{{base_path}}:{_fn_name(i)}"),')

    lines += [
        ")",
        "",
        "for name, handler in tuple_step_handler:",
        "    project.new_function(name=name, handler=handler, **shared_kwargs)",
        "",
        "workflow = project.new_workflow(",
        '    name="data-ingestion-pipeline",',
        '    kind="hera",',
        f'    code_src=f"git+{REPO_URL}#{{TAG_GITHUB}}",',
        '    handler="src.bdt_mobility.extraction.platform.workflow:pipeline",',
        ")",
        "",
        'workflow.run("build", secrets=["GIT_TOKEN"], wait=True)',
        "",
        "workflow.run(",
        '    "pipeline",',
        "    volumes=[",
        "        {",
        '            "volume_type": "persistent_volume_claim",',
        '            "name": "shared-volume",',
        '            "mount_path": "/mnt/data",',
        '            "spec": {"size": "15Gi"},',
        "        },",
        "    ],",
        '    secrets=["GIT_TOKEN"],',
        "    wait=True,",
        '    parameters={"labels": "data-ingestion"},',
        ")",
        "",
    ]

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    fp = _compute_fingerprint(PIPELINE)
    print(f"Pipeline: {len(PIPELINE)} steps  |  fingerprint: {fp}")

    targets = {
        PLATFORM_DIR / "workflow_handlers.py": _gen_handlers(PIPELINE, fp),
        PLATFORM_DIR / "workflow.py": _gen_workflow(PIPELINE, fp),
        PLATFORM_DIR / "ingest_data.py": _gen_ingest(PIPELINE, fp),
    }

    for path, content in targets.items():
        path.write_text(content)
        print(f"  Wrote {path}")

    print("Done.")


if __name__ == "__main__":
    main()
